func (s *pgStore) AddSnooze(ctx context.Context, at time.Time, msg model.PushMessage) error {
	u, err := uid(ctx)
	if err != nil {
		return err
	}
	raw, err := json.Marshal(msg)
	if err != nil {
		return err
	}
	tag, err := s.pool.Exec(ctx, `INSERT INTO snoozes (user_id, at, message)
		SELECT $1, $2, $3::jsonb WHERE (SELECT count(*) FROM snoozes WHERE user_id = $1) < $4`,
		u, at, string(raw), MaxSnoozes)
	if err != nil {
		return fmt.Errorf("отложенное уведомление: %w", err)
	}
	if tag.RowsAffected() == 0 {
		return ErrLimit
	}
	return nil
}

func (s *pgStore) TakeDueSnoozes(ctx context.Context, now time.Time) []model.Snooze {
	// DELETE … RETURNING: каждое отложенное уведомление забирает ровно один процесс.
	rows, err := s.pool.Query(ctx, `DELETE FROM snoozes WHERE at <= $1 RETURNING id, user_id, at, message::text`, now)
	if err != nil {
		return nil
	}
	out, err := pgx.CollectRows(rows, func(row pgx.CollectableRow) (model.Snooze, error) {
		var z model.Snooze
		var raw string
		if err := row.Scan(&z.ID, &z.UserID, &z.At, &raw); err != nil {
			return z, err
		}
		return z, json.Unmarshal([]byte(raw), &z.Message)
	})
	if err != nil {
		return nil
	}
	return out
}

func (s *pgStore) ServerKey(ctx context.Context, name string, gen func() (string, error)) (string, error) {
	var v string
	err := s.pool.QueryRow(ctx, `SELECT value FROM server_keys WHERE name = $1`, name).Scan(&v)
	if err == nil {
		return v, nil
	}
	if !errors.Is(err, pgx.ErrNoRows) {
		return "", fmt.Errorf("ключ сервера: %w", err)
	}
	fresh, err := gen()
	if err != nil {
		return "", err
	}
	// Два процесса могли создать ключ одновременно: побеждает первая запись, оба читают её.
	if _, err := s.pool.Exec(ctx, `INSERT INTO server_keys (name, value) VALUES ($1, $2) ON CONFLICT DO NOTHING`, name, fresh); err != nil {
		return "", fmt.Errorf("ключ сервера: %w", err)
	}
	if err := s.pool.QueryRow(ctx, `SELECT value FROM server_keys WHERE name = $1`, name).Scan(&v); err != nil {
		return "", fmt.Errorf("ключ сервера: %w", err)
	}
	return v, nil
}
