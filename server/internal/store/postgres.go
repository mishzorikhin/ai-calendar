func (s *pgStore) migrate(ctx context.Context) error {
	for _, stmt := range schema {
		if _, err := s.pool.Exec(ctx, stmt); err != nil {
			return fmt.Errorf("миграция: %w", err)
		}
	}
	return nil
}

// importJSON переносит data.json в пустую базу; если база уже с данными — пропускает.
func (s *pgStore) importJSON(ctx context.Context, dir string) error {
	if dir == "" {
		return nil
	}
	raw, err := os.ReadFile(filepath.Join(dir, "data.json"))
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("чтение данных для импорта: %w", err)
	}
	var d data
	if err := json.Unmarshal(raw, &d); err != nil {
		return fmt.Errorf("разбор %s: %w", filepath.Join(dir, "data.json"), err)
	}
	if len(d.Events) == 0 && len(d.Messages) == 0 && len(d.Tasks) == 0 {
		return nil
	}
	fresh := false
	err = s.pool.QueryRow(ctx, `
		SELECT (SELECT count(*) FROM events) = 0
		   AND (SELECT count(*) FROM messages) = 0
		   AND (SELECT count(*) FROM tasks) = 0
	`).Scan(&fresh)
	if err != nil {
		return fmt.Errorf("проверка пустоты базы: %w", err)
	}
	if !fresh {
		return nil
	}
	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback(ctx)

	for _, e := range d.Events {
		createdAt := e.CreatedAt
		if createdAt.IsZero() {
			createdAt = time.Now()
		}
		if _, err := tx.Exec(ctx, `INSERT INTO events (id, user_id, date, title, subtitle, start_min, end_min, badge, highlight, created_at)
			VALUES ($1, NULLIF($2, 0), $3, $4, $5, $6, $7, $8, $9, $10)`,
			e.ID, e.UserID, e.Date, e.Title, e.Subtitle, e.Start, e.End, e.Badge, e.Highlight, createdAt); err != nil {
			return fmt.Errorf("импорт события %s: %w", e.ID, err)
		}
	}
	for _, m := range d.Messages {
		if _, err := tx.Exec(ctx, `INSERT INTO messages (id, user_id, role, text, created_at) VALUES ($1, NULLIF($2, 0), $3, $4, $5)`,
			m.ID, m.UserID, m.Role, m.Text, m.CreatedAt); err != nil {
			return fmt.Errorf("импорт сообщения %d: %w", m.ID, err)
		}
	}
	for _, t := range d.Tasks {
		if _, err := tx.Exec(ctx, `INSERT INTO tasks (id, owner_id, title, subtitle, kind, category, done, due)
			VALUES ($1, NULLIF($2, 0), $3, $4, $5, $6, $7, $8)`,
			t.ID, t.OwnerID, t.Title, t.Subtitle, t.Kind, t.Category, t.Done, t.Due); err != nil {
			return fmt.Errorf("импорт задачи %s: %w", t.ID, err)
		}
	}
	// Сдвигаем счётчики за импортированные записи, чтобы новые id не пересекались.
	if err := bumpSequence(ctx, tx, "event_id_seq", "events", "id"); err != nil {
		return err
	}
	if err := bumpSequence(ctx, tx, "task_id_seq", "tasks", "id"); err != nil {
		return err
	}
	if _, err := tx.Exec(ctx, `SELECT setval(pg_get_serial_sequence('messages', 'id'), GREATEST((SELECT max(id) FROM messages), 0) + 1, FALSE)`); err != nil {
		return fmt.Errorf("счётчик сообщений: %w", err)
	}
	if err := tx.Commit(ctx); err != nil {
		return err
	}
	// Импорт однократный: после успеха файл убираем, иначе при следующем старте
	// (например после чистки сообщений) он импортируется повторно и уронит сервер.
	_ = os.Remove(filepath.Join(dir, "data.json"))
	return nil
}

// bumpSequence ставит последовательность за максимальный числовой суффикс значений колонки («evt-12» → 12).
func bumpSequence(ctx context.Context, tx pgx.Tx, seq, table, column string) error {
	var max int
	err := tx.QueryRow(ctx, fmt.Sprintf(
		`SELECT COALESCE(max((split_part(%s, '-', 2))::bigint), 0) FROM %s WHERE %s ~ '^[A-Za-z]+-[0-9]+$'`, column, table, column,
	)).Scan(&max)
	if err != nil {
		return fmt.Errorf("счётчик %s: %w", seq, err)
	}
	if max == 0 {
		return nil
	}
	if _, err := tx.Exec(ctx, fmt.Sprintf(`SELECT setval('%s', $1, TRUE)`, seq), max); err != nil {
		return fmt.Errorf("счётчик %s: %w", seq, err)
	}
	return nil
}

