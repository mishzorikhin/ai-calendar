func (s *pgStore) RemoveTaskMember(ctx context.Context, taskID string, memberID int64) (model.Task, error) {
	u, err := uid(ctx)
	if err != nil {
		return model.Task{}, err
	}
	t, err := s.Task(ctx, taskID)
	if err != nil {
		return model.Task{}, err
	}
	// Владелец удаляет любого, участник — только себя.
	if t.OwnerID != u && memberID != u {
		return model.Task{}, ErrForbidden
	}
	if t.OwnerID == memberID {
		return model.Task{}, badMember("владелец не может выйти из своей задачи")
	}
	tag, err := s.pool.Exec(ctx, `DELETE FROM task_members WHERE task_id = $1 AND user_id = $2`, taskID, memberID)
	if err != nil {
		return model.Task{}, fmt.Errorf("удаление участника: %w", err)
	}
	if tag.RowsAffected() == 0 {
		return model.Task{}, ErrNotFound
	}
	// Без повторного Task(ctx): вышедший участник задачу уже не видит.
	for i, m := range t.Members {
		if m.ID == memberID {
			t.Members = append(t.Members[:i], t.Members[i+1:]...)
			break
		}
	}
	return t, nil
}

