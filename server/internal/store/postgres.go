// OpenPostgres подключается к базе по dsn и готовит схему. dataDir — каталог
// со старым data.json для однократного импорта (может быть пустым).
func OpenPostgres(ctx context.Context, dsn, dataDir string) (Store, error) {
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		return nil, fmt.Errorf("разбор DATABASE_URL: %w", err)
	}
	cfg.MaxConns = 4
	cfg.ConnConfig.ConnectTimeout = 5 * time.Second
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		return nil, fmt.Errorf("подключение к базе: %w", err)
	}
	s := &pgStore{pool: pool}
	if err := s.migrate(ctx); err != nil {
		pool.Close()
		return nil, err
	}
	if err := s.importJSON(ctx, dataDir); err != nil {
		pool.Close()
		return nil, err
	}
	return s, nil
}

